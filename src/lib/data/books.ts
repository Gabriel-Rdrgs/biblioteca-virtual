interface BookSeed {
  id: string;
  title: string;
  subtitle?: string;
  authors: string[];
  publisher?: string;
  publicationYear?: number;
  edition?: string;
  isbn?: string;
  kind?: MaterialKind;
  accessType?: AccessType;
  externalUrl?: string;
  motif: CoverMotif;
  topics: string[];
  source: {
    plan: DisciplineId;
    section: string;
    page: number;
    raw: string;
    status?: ReviewStatus;
    note?: string;
  };
}

function defineBook(seed: BookSeed): Book {
  return {
    id: seed.id,
    // The id doubles as the slug: two books share the title "Semiologia
    // Médica" (Rocco and Porto) and two share "Código de Ética Médica",
    // so a title-derived slug would collide.
    slug: seed.id,
    title: seed.title,
    ...(seed.subtitle ? { subtitle: seed.subtitle } : {}),
    authors: seed.authors,
    ...(seed.publisher ? { publisher: seed.publisher } : {}),
    ...(seed.publicationYear ? { publicationYear: seed.publicationYear } : {}),
    ...(seed.edition ? { edition: seed.edition } : {}),
    ...(seed.isbn ? { isbn: seed.isbn } : {}),
    kind: seed.kind ?? "livro",
    accessType: seed.accessType ?? "institutional",
    ...(seed.externalUrl ? { externalUrl: seed.externalUrl } : {}),
    coverSource: "placeholder",
    coverMotif: seed.motif,
    topics: seed.topics,
    provenance: {
      sourcePlanId: seed.source.plan,
      sourceSection: seed.source.section,
      sourcePage: seed.source.page,
      rawCitation: seed.source.raw,
      reviewStatus: seed.source.status ?? "ok",
      ...(seed.source.note ? { reviewNote: seed.source.note } : {}),
    },
    addedAt: CATALOGUED_AT,
  };
}

